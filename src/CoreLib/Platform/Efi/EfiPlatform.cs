using System;
using System.Runtime;
using System.Runtime.CompilerServices;
using Internal.Runtime.CompilerHelpers;
using Alloy.Arch.X64;
using Alloy.Efi;

namespace Alloy.Efi
{
	public static class EfiApplication
	{
		public static unsafe void* ImageHandle { get; private set; }
		public static unsafe EfiSystemTable* SystemTable { get; private set; }

		// After ExitBootServices the pool allocator is gone; allocations must fail loudly instead of corrupting memory
		public static bool BootServicesExited { get; private set; }

		internal static unsafe void Initialize(void* imageHandle, EfiSystemTable* systemTable)
		{
			ImageHandle = imageHandle;
			SystemTable = systemTable;
		}

		public static void MarkBootServicesExited() => BootServicesExited = true;

		public static unsafe void ConsoleWrite(ReadOnlySpan<char> text)
		{
			if (BootServicesExited)
				return;

			// OutputString wants a null-terminated string, so send it in chunks through a terminated stack buffer
			char* buffer = stackalloc char[129];
			while (text.Length > 0)
			{
				int count = 0;
				for (; count < 128 && count < text.Length; count++)
					buffer[count] = text[count];
				buffer[count] = '\0';
				SystemTable->ConOut->OutputString(SystemTable->ConOut, buffer);
				text = text.Slice(count);
			}
		}
	}
}

namespace Internal.Runtime.CompilerHelpers
{
	internal static class EfiStartup
	{
		// Generated by ILC for the image's Main; runs RunModuleInitializers and then Main
		[RuntimeImport("*", "__managed__Main")]
		[MethodImpl(MethodImplOptions.InternalCall)]
		private static extern unsafe int ManagedMain(int argc, char** argv);

		[RuntimeExport("EfiMain")]
		private static unsafe ulong EfiMain(void* imageHandle, EfiSystemTable* systemTable)
		{
			EfiApplication.Initialize(imageHandle, systemTable);

			// Firmware arms a five minute watchdog for boot applications; disable it so a debugging session isn't reset
			systemTable->BootServices->SetWatchdogTimer(0, 0, 0, null);

			Environment.SetFailFastWriter(&WriteFailFast);
			StartupCodeHelpers.InitializeModules();
			return (ulong)ManagedMain(0, null);
		}

		private static void WriteFailFast(string message)
		{
			EfiApplication.ConsoleWrite(message);
			EfiApplication.ConsoleWrite("\r\n");
		}
	}
}

namespace System.Runtime
{
	internal static partial class Allocator
	{
		private static unsafe partial void* AllocateZeroed(nuint size)
		{
			if (EfiApplication.BootServicesExited)
				Environment.FailFast("FAILFAST: allocation after ExitBootServices");

			void* memory;
			if (EfiApplication.SystemTable->BootServices->AllocatePool(EfiMemoryType.LoaderData, size, &memory) != EfiStatus.Success)
				return null;
			SpanHelpers.ClearWithoutReferences(ref *(byte*)memory, size);
			return memory;
		}

		private static unsafe partial void Free(void* memory)
		{
			if (!EfiApplication.BootServicesExited)
				EfiApplication.SystemTable->BootServices->FreePool(memory);
		}
	}
}

namespace System.Threading
{
	// The loader has one thread, so a lock is never contended
	public static partial class Monitor
	{
		private static unsafe partial uint CurrentThreadId() => 1;

		private static unsafe partial void Yield() => Environment.FailFast("FAILFAST: a lock contended with a single thread");
	}
}

namespace System
{
	public static partial class Environment
	{
		private static partial void Halt() => Cpu.HaltForever();
	}
}
